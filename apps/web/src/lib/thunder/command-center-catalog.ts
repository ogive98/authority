function inst(
  id: string,
  widgetDefinitionId: string,
  order: number,
  x: number,
  y: number,
  w: number,
  h: number,
): WidgetInstance {
  return {
    id,
    widgetDefinitionId,
    dashboardId: "thunder.command-center",
    position: { x, y, w, h },
    configuration: {},
    visibility: true,
    order,
  };
}

