function def(
  partial: Omit<WidgetDefinition, "version" | "enabled" | "module"> & {
    module?: string;
  },
): WidgetDefinition {
  return {
    version: "1.0.0",
    enabled: true,
    module: partial.module ?? "thunder",
    ...partial,
  };
}

